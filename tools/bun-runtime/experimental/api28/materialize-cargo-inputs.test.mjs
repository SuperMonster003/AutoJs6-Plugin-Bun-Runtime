const experimentRoot = dirname(fileURLToPath(import.meta.url));

test("Cargo.lock parsing returns only checksummed crates.io packages", () => {
  const parsed = parseCargoLock(`# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "local-package"\nversion = "1.0.0"\n\n[[package]]\nname = "registry-package"\nversion = "2.3.4"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "${"a".repeat(64)}"\n`);
  assert.equal(parsed.packages.length, 2);
  assert.deepEqual(parsed.registryPackages, [{
    name: "registry-package",
    version: "2.3.4",
    sha256: "a".repeat(64),
  }]);
  assert.equal(parsed.gitSourceCount, 0);
});

test("Cargo.lock parsing rejects missing registry checksums and duplicate identities", () => {
  assert.throws(
    () => parseCargoLock(`version = 4\n\n[[package]]\nname = "missing"\nversion = "1.0.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`),
    /checksum is missing or invalid/,
  );
  assert.throws(
    () => parseCargoLock(`version = 4\n\n[[package]]\nname = "same"\nversion = "1.0.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "${"a".repeat(64)}"\n\n[[package]]\nname = "same"\nversion = "1.0.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "${"a".repeat(64)}"\n`),
    /Duplicate Cargo registry package/,
  );
});

test("Cargo.lock parsing inventories Git sources so resolution can reject them", () => {
  const parsed = parseCargoLock(`version = 4\n\n[[package]]\nname = "git-package"\nversion = "1.0.0"\nsource = "git+https://example.invalid/repository#${"b".repeat(40)}"\n`);
  assert.equal(parsed.gitSourceCount, 1);
  assert.equal(parsed.registryPackages.length, 0);
});

test("Cargo registry packages from the workspace and Rust standard library form a checksum-consistent union", () => {
  const shared = { name: "shared", version: "1.0.0", sha256: "a".repeat(64) };
  const merged = mergeCargoRegistryPackages(
    [shared, { name: "workspace", version: "2.0.0", sha256: "b".repeat(64) }],
    [shared, { name: "rust-std", version: "3.0.0", sha256: "c".repeat(64) }],
  );
  assert.equal(merged.referenceCount, 4);
  assert.equal(merged.sharedIdentityCount, 1);
  assert.deepEqual(merged.registryPackages.map(({ name }) => name), ["rust-std", "shared", "workspace"]);
  assert.throws(
    () => mergeCargoRegistryPackages([shared], [{ ...shared, sha256: "d".repeat(64) }]),
    /disagree on the registry checksum/,
  );
});

test("the checked-in Cargo archive lock is complete, canonical, and byte-locked", () => {
  const lock = JSON.parse(readFileSync(resolve(experimentRoot, "cargo-inputs.lock.json"), "utf8"));
  const artifacts = collectCargoArtifacts(lock);
  assert.equal(artifacts.length, 206);
  assert.equal(artifacts.reduce((total, artifact) => total + artifact.bytes, 0), lock.totalArchiveBytes);
});

test("a locked Cargo archive is accepted offline and byte drift is rejected", async () => {
  await withFixture(async ({ artifact, bytes, lockPath, output }) => {
    const archives = resolve(output, "archives");
    mkdirSync(archives, { recursive: true });
    writeFileSync(resolve(archives, artifact.filename), bytes);
    const result = await materializeCargoInputs({ outputDirectory: output, offline: true, lockPath });
    assert.equal(result.artifacts.length, 1);
    assert.equal(result.artifacts[0].source, "existing");

    writeFileSync(resolve(archives, artifact.filename), "drift\n");
    await assert.rejects(
      materializeCargoInputs({ outputDirectory: output, offline: true, lockPath }),
      /expected .* bytes/,
    );
  });
});

test("a noncanonical Cargo archive URL and unsafe version are rejected", async () => {
  await withFixture(async ({ lockPath, output }) => {
    const lock = JSON.parse(readFileSync(lockPath, "utf8"));
    lock.archives[0].url = "https://example.invalid/fixture.crate";
    writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
    await assert.rejects(
      materializeCargoInputs({ outputDirectory: output, offline: true, lockPath }),
      /URL is not canonical/,
    );
  });

  await withFixture(async ({ lockPath, output }) => {
    const lock = JSON.parse(readFileSync(lockPath, "utf8"));
    lock.archives[0].version = "../escape";
    writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
    await assert.rejects(
      materializeCargoInputs({ outputDirectory: output, offline: true, lockPath }),
      /version is invalid/,
    );
  });
});

test("locked .crate files produce a reusable and drift-checked Cargo directory source", async () => {
  await withCrateFixture(async ({ artifact, lockPath, output }) => {
    const result = await materializeCargoInputs({
      outputDirectory: output,
      offline: true,
      prepareDirectorySource: true,
      lockPath,
    });
    assert.equal(result.directorySource.source, "created");
    assert.equal(result.directorySource.packageCount, 1);
    assert.match(result.directorySource.configPath, /config\.toml$/);
    assert.match(readFileSync(result.directorySource.configPath, "utf8"), /offline = true/);
    const packageRoot = resolve(output, "vendor", "fixture-crate-1.2.3");
    const checksum = JSON.parse(readFileSync(resolve(packageRoot, ".cargo-checksum.json"), "utf8"));
    assert.equal(checksum.package, artifact.sha256);
    assert.match(checksum.files["src/lib.rs"], /^[0-9a-f]{64}$/);

    const reused = await materializeCargoInputs({
      outputDirectory: output,
      offline: true,
      prepareDirectorySource: true,
      lockPath,
    });
    assert.equal(reused.directorySource.source, "existing");

    writeFileSync(resolve(packageRoot, "src/lib.rs"), "pub fn drift() {}\n");
    await assert.rejects(
      materializeCargoInputs({
        outputDirectory: output,
        offline: true,
        prepareDirectorySource: true,
        lockPath,
      }),
      /Cargo vendor file drifted/,
    );
  });
});

