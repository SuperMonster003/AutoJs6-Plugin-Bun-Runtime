async function withCrateFixture(callback) {
  const root = mkdtempSync(resolve(tmpdir(), "autojs6-cargo-directory-source-test-"));
  try {
    const packageRoot = "fixture-crate-1.2.3";
    const content = resolve(root, "content", packageRoot);
    mkdirSync(resolve(content, "src"), { recursive: true });
    writeFileSync(resolve(content, "Cargo.toml"), "[package]\nname = \"fixture-crate\"\nversion = \"1.2.3\"\nedition = \"2021\"\n");
    writeFileSync(resolve(content, "src/lib.rs"), "pub fn fixture() {}\n");
    const output = resolve(root, "materialized");
    const archiveDirectory = resolve(output, "archives");
    mkdirSync(archiveDirectory, { recursive: true });
    const archive = resolve(archiveDirectory, `${packageRoot}.crate`);
    const tarExecutable = process.platform === "win32" && process.env.SystemRoot
      ? resolve(process.env.SystemRoot, "System32", "tar.exe")
      : "tar";
    const tar = spawnSync(tarExecutable, ["-czf", archive, "-C", resolve(root, "content"), packageRoot], {
      encoding: "utf8",
      windowsHide: true,
    });
    if (tar.error) throw tar.error;
    assert.equal(tar.status, 0, tar.stderr);
    assert.equal(existsSync(archive), true);
    const bytes = readFileSync(archive);
    const artifact = {
      name: "fixture-crate",
      version: "1.2.3",
      filename: `${packageRoot}.crate`,
      url: `https://static.crates.io/crates/fixture-crate/${packageRoot}.crate`,
      bytes: bytes.length,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    };
    const lockPath = resolve(root, "cargo-inputs.lock.json");
    writeFileSync(lockPath, `${JSON.stringify(createFixtureLock(artifact), null, 2)}\n`);
    await callback({ artifact, lockPath, output });
  } finally {
    rmSync(root, { force: true, recursive: true });
  }
}

