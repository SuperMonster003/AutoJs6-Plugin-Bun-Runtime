// Encodes a result as JSON-safe data, the same way in Rhino and Node; javaInfo(v) returns the class name of a Java
// value (a Rhino Java object, a Node Java handle), "list" with the elements for a Java list, or null.
function jsToolsEncode(v, javaInfo, depth) {
    depth = depth || 0;
    if (depth > 6) return {deep: 1};
    if (v === undefined) return {u: 1};
    if (v === null) return null;
    var t = typeof v;
    if (t === "boolean" || t === "string") return v;
    if (t === "number") {
        v = +v;
        if (v !== v) return {n: "NaN"};
        if (v === Infinity) return {n: "Infinity"};
        if (v === -Infinity) return {n: "-Infinity"};
        if (v === 0 && 1 / v < 0) return {n: "-0"};
        return v;
    }
    if (t === "bigint") return {big: String(v)};
    if (t === "symbol") return {sym: String(v)};
    var java = javaInfo ? javaInfo(v) : null;
    if (java) {
        if (java.list) {
            var items = [];
            for (var k = 0; k < java.list.length; k++) items.push(jsToolsEncode(java.list[k], javaInfo, depth + 1));
            return {list: items};
        }
        return {java: java.className};
    }
    if (t === "function") return {fn: 1};
    if (Array.isArray(v)) {
        var out = [];
        for (var i = 0; i < v.length; i++) out.push(i in v ? jsToolsEncode(v[i], javaInfo, depth + 1) : {hole: 1});
        return out;
    }
    if (v instanceof Date) return {date: v.getTime()};
    if (v instanceof RegExp) return {re: String(v)};
    if (v instanceof Error) return {err: String(v.name), msg: String(v.message)};
    var keys = Object.keys(v).sort();
    var o = {};
    for (var j = 0; j < keys.length; j++) o[keys[j]] = jsToolsEncode(v[keys[j]], javaInfo, depth + 1);
    return {o: o};
}

// The thrown value of a case as {name, message}.
function jsToolsThrown(e) {
    var name = e && e.name ? String(e.name) : Object.prototype.toString.call(e);
    if (e && e.javaException) name = "JavaException " + String(e.javaException.getClass().getSimpleName());
    return {name: name, message: String(e && e.message !== undefined ? e.message : e)};
}

